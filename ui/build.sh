#!/usr/bin/env bash
# Build the Gnomon web UI (a Rune app) into ui/dist, for gnomon-web --ui-dir ui/dist.
#
#   ui/build.sh            # release build
#   ui/build.sh --dev      # fast, unoptimized build
#   ui/build.sh --watch    # rebuild on change (with --dev); the page reloads itself
#
# Needs: rustup (the toolchain in ui/rust-toolchain.toml is installed on first use, with the
# wasm32 target), wasm-bindgen-cli 0.2.129 (`cargo install wasm-bindgen-cli --version 0.2.129
# --locked`), python3 >= 3.11 and git. Rune's build script and fonts come from a checkout of Rune
# at the same revision as ui/Cargo.toml, kept in ui/.rune (git-ignored).
set -euo pipefail
cd "$(dirname "$0")"
rev=$(sed -n 's/^rune = .*rev = "\([0-9a-f]*\)".*/\1/p' Cargo.toml)
[ -n "$rev" ] || { echo "build.sh: no Rune rev in ui/Cargo.toml" >&2; exit 2; }

if [ "$(git -C .rune rev-parse HEAD 2>/dev/null || true)" != "$rev" ]; then
  echo "== fetching Rune $rev into ui/.rune"
  rm -rf .rune
  git init -q .rune
  git -C .rune remote add origin https://github.com/anomalyco/rune
  git -C .rune fetch -q --depth 1 origin "$rev"
  git -C .rune checkout -q FETCH_HEAD
fi

command -v wasm-bindgen >/dev/null || {
  echo "build.sh: wasm-bindgen not found: cargo install wasm-bindgen-cli --version 0.2.129 --locked" >&2
  exit 2
}
rustup target add wasm32-unknown-unknown >/dev/null 2>&1 || true

# Rune's script builds one cdylib of this workspace with the toolchain's own cargo, runs
# wasm-bindgen and copies the fonts next to app.js. Our index.html (with the brand colours
# and favicon before the wasm loads) is kept: it lacks the "generated by" marker.
mkdir -p dist
case " $* " in
  *" --watch "*) rm -f dist/index.html ;;   # watch mode: Rune's generated, self-reloading page
  *) cp web/index.html dist/index.html ;;
esac
cp ../assets/logo/png/gnomon-icon-64.png dist/favicon.png 2>/dev/null || true
# The brand fonts (JetBrains Mono, Space Grotesk) are compiled into the wasm (app/src/theme.rs);
# the copies here are for the loading page's CSS.
mkdir -p dist/fonts && cp assets/fonts/*.ttf dist/fonts/
exec .rune/scripts/web-build.sh gnomon-ui --out dist "$@"
